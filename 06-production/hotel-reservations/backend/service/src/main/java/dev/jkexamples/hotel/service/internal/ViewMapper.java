package dev.jkexamples.hotel.service.internal;

import dev.jkexamples.hotel.contract.DeskReservation;
import dev.jkexamples.hotel.contract.HotelDetail;
import dev.jkexamples.hotel.contract.HotelSummary;
import dev.jkexamples.hotel.contract.MoneyView;
import dev.jkexamples.hotel.contract.NightlyPrice;
import dev.jkexamples.hotel.contract.Offer;
import dev.jkexamples.hotel.contract.ReservationView;
import dev.jkexamples.hotel.contract.RoomTypeView;
import dev.jkexamples.hotel.core.Hotel;
import dev.jkexamples.hotel.core.Money;
import dev.jkexamples.hotel.core.Quote;
import dev.jkexamples.hotel.core.Reservation;
import dev.jkexamples.hotel.core.RoomType;
import java.util.List;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingConstants;
import org.mapstruct.ReportingPolicy;

/**
 * Domain objects to the contract's DTOs, generated by MapStruct at compile time: no reflection at
 * run time, and a contract field nothing maps fails the build ({@code unmappedTargetPolicy}).
 */
@Mapper(componentModel = MappingConstants.ComponentModel.SPRING, unmappedTargetPolicy = ReportingPolicy.ERROR)
interface ViewMapper {

    MoneyView money(Money money);

    @Mapping(target = "fromPrice", source = "fromPrice")
    HotelSummary summary(Hotel hotel, Money fromPrice);

    @Mapping(target = "roomTypes", source = "roomTypes")
    HotelDetail detail(Hotel hotel, List<RoomType> roomTypes);

    RoomTypeView roomType(RoomType roomType);

    @Mapping(target = "night", source = "date")
    NightlyPrice night(Quote.Night night);

    @Mapping(target = "roomType", source = "roomType")
    @Mapping(target = "roomsLeft", source = "roomsLeft")
    @Mapping(target = "nights", source = "quote.nights")
    @Mapping(target = "subtotal", source = "quote.subtotal")
    @Mapping(target = "discount", source = "quote.discount")
    @Mapping(target = "taxes", source = "quote.taxes")
    @Mapping(target = "total", source = "quote.total")
    Offer offer(RoomType roomType, int roomsLeft, Quote quote);

    @Mapping(target = "status", source = "reservation.status")
    @Mapping(target = "hotelSlug", source = "hotel.slug")
    @Mapping(target = "hotelName", source = "hotel.name")
    @Mapping(target = "checkIn", source = "reservation.stay.checkIn")
    @Mapping(target = "checkOut", source = "reservation.stay.checkOut")
    @Mapping(target = "nights", expression = "java(reservation.stay().nights())")
    @Mapping(target = "adults", source = "reservation.party.adults")
    @Mapping(target = "children", source = "reservation.party.children")
    @Mapping(target = "guestName", expression = "java(reservation.guest().fullName())")
    @Mapping(target = "guestEmail", source = "reservation.guest.email")
    @Mapping(target = "total", source = "reservation.total")
    @Mapping(target = "specialRequests", source = "reservation.specialRequests")
    @Mapping(target = "confirmationCode", source = "reservation.confirmationCode")
    @Mapping(target = "roomTypeName", source = "reservation.roomTypeName")
    @Mapping(target = "roomNumber", source = "reservation.roomNumber")
    @Mapping(target = "bookedAt", source = "reservation.bookedAt")
    ReservationView reservation(Reservation reservation, Hotel hotel, boolean cancellable);

    @Mapping(target = "status", source = "status")
    @Mapping(target = "guestName", expression = "java(reservation.guest().fullName())")
    @Mapping(target = "checkIn", source = "stay.checkIn")
    @Mapping(target = "checkOut", source = "stay.checkOut")
    @Mapping(target = "guests", expression = "java(reservation.party().size())")
    DeskReservation desk(Reservation reservation);
}
